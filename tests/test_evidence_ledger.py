def test_scope_and_purity(tmp_path):
    before = {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in SAVED}
    row = json.loads((ROOT / 'demo/recordings/demo_mill_one-result.json').read_text())['rows'][0]
    assert all(e['field'] in el.DELIVERY_FIELDS for e in el.entries_from_row(row))
    assert 'product_price' not in {e['field'] for e in el.entries_from_row(row)}
    first = el.ledger_for_result(json.loads((ROOT / 'demo/recordings/demo_mill_one-result.json').read_text()))
    second = el.ledger_for_result(json.loads((ROOT / 'demo/recordings/demo_mill_one-result.json').read_text()))
    assert json.dumps(first, sort_keys=True) == json.dumps(second, sort_keys=True)  # deterministic
    out = tmp_path / 'ledger.json'
    cli = [sys.executable, '-S', str(ROOT / 'scripts' / 'evidence_ledger.py'),
           'demo/recordings/demo_mill_one-result.json', '--output', str(out)]
    assert subprocess.run(cli, cwd=ROOT, capture_output=True).returncode == 0 and out.is_file()
    again = subprocess.run(cli, cwd=ROOT, capture_output=True, text=True)
    assert again.returncode != 0 and 'refusing to overwrite' in again.stderr
    onto_input = subprocess.run(cli[:-1] + ['demo/recordings/demo_mill_one-result.json'], cwd=ROOT,
                                capture_output=True, text=True)
    assert onto_input.returncode != 0 and 'input' in onto_input.stderr
    assert {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in SAVED} == before
    source = (ROOT / 'scout' / 'evidence_ledger.py').read_text()
    for forbidden in ('import socket', 'urllib.request', 'http.client', 'playwright', 'scout.engine', 'scout.plain',
                      'open(', 'requests'):
        assert forbidden not in source, forbidden
    assert set(el.NOT_CLAIMED) == {'rule membership', 'applicability', 'option identity', 'footnote coverage',
                                   'source currentness', 'completeness', 'net or gross tax/weight',
                                   'free means zero total', 'eligibility', 'delivered totals', 'ranking',
                                   'buyer validation'}


# -- v1.5.1 provenance controls (outside the 19 protocol categories; added after independent diagnostics) --------------
_ABSENT = object()


def _with_url(base, url):
    return dict(base) if url is _ABSENT else dict(base, source_url=url)


@pytest.mark.parametrize('identity', [_ABSENT, '', None, '   ', '\t\n', '#only-a-fragment'],
                         ids=['absent', 'empty', 'null', 'spaces', 'whitespace', 'fragment-only'])
def test_missing_source_identity_never_matches_or_groups(identity):
    q = 'INVENTED: free delivery over £50 in Zone A'
    entries = [_with_url({'field': 'free_delivery_threshold', 'key': k, 'value': v, 'quote': q}, identity)
               for k, v in (('amount', '£50'), ('comparison', 'over'))]
    ledger = el.build_ledger(entries, [_with_url({'text': q}, identity)])
    assert len(ledger['observations']) == 2  # entries are kept
    for o in ledger['observations']:
        assert o['source_match'] == 'no_source_identity' and o['location_status'] == 'source_identity_missing'
        assert o['source_candidates'] == [] and o['occurrences'] == []
    assert ledger['same_quote_span_groups'] == []
    src = ledger['sources'][0]
    assert src['source_identity'] == 'missing' and src['text_sha256'] == el.text_sha256(q)  # saved text kept


