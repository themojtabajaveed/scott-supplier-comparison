# -- protocol: invented LAB A/B cases --------------------------------------------------------------------------------
def test_same_policy_positive():
    ledger = lab()
    assert len(ledger['observations']) == 6
    assert all(o['location_status'] == 'located_unique' for o in ledger['observations'])
    assert len(ledger['same_quote_span_groups']) == 1
    g = ledger['same_quote_span_groups'][0]
    assert len(g['observations']) == 6 and (g['start'], g['end']) == (0, len(QA))
    assert g['meaning'] == 'quoted from one unique saved span; not evidence of one shipping rule'


@pytest.mark.parametrize('key', ['comparison', 'zone', 'weight_limit', 'discount_condition', 'exceptions'])
def test_cross_policy_swaps(key):
    ledger = lab(swap=key)
    changed, amount = obs(ledger, key)[0], obs(ledger, 'amount')[0]
    assert changed['location_status'] == 'located_unique' and changed['occurrences'][0]['start'] == len(QA) + 1
    assert group_of(ledger, changed['observation_id']) is None  # never joins the amount
    a_group = group_of(ledger, amount['observation_id'])
    assert a_group and len(a_group['observations']) == 5 and changed['observation_id'] not in a_group['observations']


def test_missing_weight_control():
    ledger = lab(drop='weight_limit', text=QA)
    assert obs(ledger, 'weight_limit') == [] and len(ledger['observations']) == 5
    assert len(ledger['same_quote_span_groups'][0]['observations']) == 5


