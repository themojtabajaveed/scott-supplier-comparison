from scout import evidence_ledger as el  # noqa: E402

SAVED = None  # the real recorded results are not included; see SYNTHETIC_SAVED (set below)
QA = ('INVENTED LAB A: free delivery for orders over GBP 50 in Zone A, up to 20kg, after discounts, excluding Zone C.')
QB = ('INVENTED LAB B: free delivery for orders at least GBP 100 in Zone B, up to 5kg, before discounts, '
      'excluding Zone A.')
LAB_URL = 'https://threshold-lab.example/policy'
A_VALUES = {'amount': 'GBP 50', 'comparison': 'over', 'zone': 'Zone A', 'weight_limit': 'up to 20kg',
            'discount_condition': 'after discounts', 'exceptions': 'excluding Zone C'}
B_VALUES = {'comparison': 'at least', 'zone': 'Zone B', 'weight_limit': 'up to 5kg',
            'discount_condition': 'before discounts', 'exceptions': 'excluding Zone A'}


def lab(swap=None, drop=None, text=QA + '\n' + QB):
    entries = []
    for key, value in A_VALUES.items():
        if key == drop:
            continue
        quote = QA
        if key == swap:
            value, quote = B_VALUES[key], QB
        entries.append({'field': 'free_delivery_threshold', 'key': key, 'value': value, 'quote': quote,
                        'source_url': LAB_URL})
    return el.build_ledger(entries, [{'source_url': LAB_URL, 'text': text}])


def obs(ledger, key):
    return [o for o in ledger['observations'] if o['key'] == key]


def group_of(ledger, observation_id):
    return next((g for g in ledger['same_quote_span_groups'] if observation_id in g['observations']), None)


# The two saved-evidence positives run on the invented demo recordings (tests/demo_suppliers.py, generated by
