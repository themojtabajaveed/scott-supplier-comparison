def test_fragment_fallback():
    q = 'Free delivery over £50'
    one = el.build_ledger([{'field': 'f', 'key': 'amount', 'value': '£50', 'quote': q, 'source_url': LAB_URL + '#tab'}],
                          [{'source_url': LAB_URL, 'text': q}])['observations'][0]
    assert (one['source_url_raw'], one['document_address'], one['fragment']) == (LAB_URL + '#tab', LAB_URL, 'tab')
    assert one['source_match'] == 'fragmentless_unique' and one['location_status'] == 'located_unique'
    exact = el.build_ledger([{'field': 'f', 'key': 'amount', 'value': '£50', 'quote': q, 'source_url': LAB_URL + '#tab'}],
                            [{'source_url': LAB_URL, 'text': q}, {'source_url': LAB_URL + '#tab', 'text': q}])
    assert exact['observations'][0]['source_match'] == 'exact_url' and exact['observations'][0]['source_candidates'] == [1]
    two = el.build_ledger([{'field': 'f', 'key': 'amount', 'value': '£50', 'quote': q, 'source_url': LAB_URL + '#x'}],
                          [{'source_url': LAB_URL, 'text': q}, {'source_url': LAB_URL + '#y', 'text': q}])
    assert two['observations'][0]['source_match'] == 'fragmentless_multiple'
    assert two['observations'][0]['location_status'] == 'source_ambiguous'


