SAVED = SYNTHETIC_SAVED  # invented demo recordings stand in for the recorded results


def saved_ledgers(saved=None):
    out = {}
    for path, digest in (saved or SAVED).items():
        data = (ROOT / path).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            pytest.fail('saved result changed: %s' % path)
        name = path.split('/')[-1].split('-result')[0]
        out[name] = el.ledger_for_result(json.loads(data))['rows'][0]
    return out


