def test_unicode_crlf_overlap():
    text = '🚚 Delivery £3.85\r\nabab ababa'
    ledger = el.build_ledger([{'field': 'f', 'key': 'amount', 'value': '£3.85', 'quote': '£3.85', 'source_url': LAB_URL},
                              {'field': 'f', 'key': 'zone', 'value': 'aba', 'quote': 'aba', 'source_url': LAB_URL}],
                             [{'source_url': LAB_URL, 'text': text}])
    amount, zone = ledger['observations']
    assert amount['occurrences'] == [{'source_index': 0, 'start': 11, 'end': 16}]  # code points, emoji counts once
    assert text[11:16] == '£3.85'
    assert text[16:18] == '\r\n'  # kept as saved
    assert [(x['start'], x['end']) for x in zone['occurrences']] == [(18, 21), (23, 26), (25, 28)]  # overlapping
    assert all(text[x['start']:x['end']] == 'aba' for x in zone['occurrences'])
    token = ledger['sources'][0]['money_tokens'][0]
    assert (token['start'], token['end'], token['line']) == (11, 16, '🚚 Delivery £3.85')  # CRLF not normalised
    assert ledger['sources'][0]['text_sha256'] == hashlib.sha256(text.encode('utf-8')).hexdigest()


